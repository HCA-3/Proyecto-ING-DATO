from pyspark.sql import SparkSession

spark = (
    SparkSession.builder
    .appName("PracticaIngenieriaDatos")
    .master("local[*]")
    .getOrCreate()
)

datos = [
    (1, "Bogota", "Portatil", 2500000, 2),
    (2, "Cali", "Mouse", 50000, 5),
    (3, "Bogota", "Teclado", 120000, 3),
    (4, "Medellin", "Monitor", 850000, 2),
    (5, "Cali", "Portatil", 2500000, 1),
    (6, "Bogota", "Mouse", 50000, 10)
]

columnas = ["id", "ciudad", "producto", "precio", "cantidad"]
df = spark.createDataFrame(datos, columnas)

df.show()
df.printSchema()

from pyspark. sql. functions import col

ventas_altas = df.filter(col("precio") >= 100000)

ventas_calculadas = ventas_altas.withColumn(
"total_venta",
col("precio") * col("cantidad")

)
ventas_calculadas.select(
"ciudad", "producto", "total_venta"
).show()

print("Total de registros:", df.count())

ventas_calculadas.groupBy("ciudad").sum(
"total_venta"
).show()