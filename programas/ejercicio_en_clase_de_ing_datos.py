from pyspark.sql import SparkSession
from pyspark.sql.functions import col, avg, sum

spark = SparkSession.builder \
    .appName("AnalisisDomicilios") \
    .getOrCreate()

datos_pedidos = [
    (1, "Este", 18000, 25, "Entregado"),
    (2, "Sur", 32000, 55, "Entregado"),
    (3, "Centro", 15000, 15, "Entregado"),
    (4, "Norte", 42000, 30, "Entregado"),
    (5, "Oeste", 28000, 50, "Pendiente"),
    (6, "Este", 21000, 20, "Entregado"),
    (7, "Sur", 13000, 65, "Entregado"),
    (8, "Centro", 55000, 12, "Entregado"),
    (9, "Norte", 11000, 45, "Cancelado"),
    (10, "Oeste", 39000, 35, "Entregado")
]

columnas = ["Pedido", "Zona", "Valor_Pedido", "Minutos_Entrega", "Estado"]

df_pedidos = spark.createDataFrame(datos_pedidos, schema=columnas)

print("--- Nueva tabla de pedidos iniciales ---")
df_pedidos.show()

# 3. Evaluar las entregas (Tiempos de entrega)
print("Tiempo promedio de entrega de pedidos entregados")
df_entregados = df_pedidos.filter(col("Estado") == "Entregado")
tiempo_promedio = df_entregados.select(avg("Minutos_Entrega")).collect()[0][0]

print(f"El tiempo promedio de entrega es de: {tiempo_promedio:.2f} minutos\n")

# Identificar pedidos con demora (por ejemplo, más de 40 minutos)
print("--- Pedidos con demoras (Más de 40 minutos) ---")
df_demorados = df_pedidos.filter((col("Minutos_Entrega") > 40) & (col("Estado") == "Entregado"))
df_demorados.show()

# 4. Analizar por Zona
print("Ingresos totales y tiempo promedio de entrega por zona")
df_zonas = df_pedidos.groupBy("Zona").agg(
    sum("Valor_Pedido").alias("Ingresos_Totales"),
    avg("Minutos_Entrega").alias("Promedio_Minutos")
).orderBy(col("Ingresos_Totales").desc())

df_zonas.show()

# 5. Aplicar Filtros Específicos
print("--- Pedidos cancelados o pendientes ---")
# Filtramos los pedidos que no se completaron con éxito
df_no_completados = df_pedidos.filter(col("Estado").isin("Cancelado", "Pendiente"))
df_no_completados.show()

print("--- Pedidos de alto valor (Mayor a $20,000) en la zona norte ---")
df_alto_valor_norte = df_pedidos.filter((col("Valor_Pedido") > 20000) & (col("Zona") == "Norte"))
df_alto_valor_norte.show()

