"""```markdown
## 3. Identificación de Situaciones Prioritarias

### Definición del Criterio de Prioridad
Para optimizar los recursos del centro de control, debemos definir una regla clara de atención inmediata.
Estableceremos que un reporte es **Prioritario** si cumple con las siguientes condiciones concurrentes:
1. **Nivel del Reporte (Gravedad):** Debe ser clasificado como `'Alto'` o `'Crítico'`, lo que denota un impacto directo en el flujo de la vía.
2. **Demora Estimada:** Situaciones con demoras superiores a **30 minutos**, ya que representan pérdidas importantes de tiempo para los usuarios de la red de transporte.

Implementamos este filtro sobre nuestro conjunto de datos.
```
"""

from pyspark.sql.functions import col

# Filtrado de registros prioritarios basados en el criterio establecido
reportes_prioritarios = reportes_df.filter(
    (col("nivel_reporte").isin("Alto", "Crítico")) &
    (col("demora_estimada_minutos") > 30)
)

# Verificación de la cantidad de registros que requieren atención prioritaria
cantidad_prioritarios = reportes_prioritarios.count()
print(f"Número de casos prioritarios detectados: {cantidad_prioritarios} ({(cantidad_prioritarios/total_registros)*100:.2f}% del total)")

# Visualización de algunos de estos reportes críticos
reportes_prioritarios.select("localidad", "via", "tipo_reporte", "nivel_reporte", "demora_estimada_minutos").show(10, truncate=False)

"""```markdown
## 4. Comparación por Localidad y Vía

Analizaremos la distribución espacial de los incidentes para saber qué zonas concentran los problemas, y evaluaremos el promedio de demora según las principales vías afectadas.
```
"""

from pyspark.sql.functions import avg, desc, count

# Resumen 1: Cantidad de reportes prioritarios por localidad
print("Distribución de casos prioritarios por Localidad:")
resumen_localidades = reportes_prioritarios.groupBy("localidad") \
    .agg(count("*").alias("total_casos_prioritarios")) \
    .orderBy(desc("total_casos_prioritarios"))

resumen_localidades.show(15, truncate=False)

# Resumen 2: Demoras promedio registradas según las vías principales afectadas en los casos prioritarios
print("Análisis de demoras promedio por Vía (Casos Prioritarios):")
resumen_vias = reportes_prioritarios.groupBy("via") \
    .agg(avg("demora_estimada_minutos").alias("promedio_demora_minutos"), count("*").alias("cantidad_incidentes")) \
    .orderBy(desc("promedio_demora_minutos"))

