def leer_documento_docx(ruta_archivo):
    doc = docx.Document(ruta_archivo)
    texto_completo = []
    for parrafo in doc.paragraphs:
        if parrafo.text.strip():
            texto_completo.append(parrafo.text.strip())
    return "\n".join(texto_completo)

