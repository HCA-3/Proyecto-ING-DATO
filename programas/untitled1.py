import pandas as pd
import numpy as np

df = pd.read_csv("aug_test.csv")

print("Primeras filas del dataset:")
print(df.head())
print("\nNúmero de filas y columnas:")
print(df.shape)
print("\nInformación del dataset:")
print(df.info())
print("\nValores nulos antes de la transformación:")
print(df.isna().sum())
print("\nFilas duplicadas:")
print(df.duplicated().sum())
print("\nEstadísticas descriptivas:")
print(df.describe())

# Transformación 1: Rellenar valores nulos en 'gender' con la moda
mode_gender = df['gender'].mode()[0]
df['gender'].fillna(mode_gender, inplace=True)

# Transformación 2: Rellenar valores nulos en 'experience' con la moda
# La columna 'experience' es de tipo objeto y contiene valores como '<1' o '>20'
mode_experience = df['experience'].mode()[0]
df['experience'].fillna(mode_experience, inplace=True)

print("\nValores nulos después de la transformación:")
print(df.isna().sum())

# data limpio
df.to_csv('aug_test_cleaned.csv', index=False)
print("DataFrame limpio guardado como 'aug_test_cleaned.csv'")